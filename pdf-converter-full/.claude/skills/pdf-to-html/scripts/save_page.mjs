#!/usr/bin/env node
/**
 * Save the generated page-root HTML fragment + scoped CSS into the
 * conventional on-disk layout:
 *
 *   <out-root>/<run-slug>/page_<n>/
 *     ├── content.html
 *     └── css/page.css
 *
 * Run-slug is derived from the PDF filename + a short content hash so
 * re-runs don't silently overwrite earlier output.
 *
 * Usage:
 *   node save_page.mjs --html <fragment-file>
 *                      --css <css-file>
 *                      --out-root <dir>
 *                      --run-id <string-or-pdf-name>
 *                      --page 3
 *                      [--work-dir <work-dir>]
 *                      [--pdf-for-hash <pdf-path>]
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";

function parseArgs(argv) {
  const out = {};
  for (let i = 2; i < argv.length; i++) {
    const k = argv[i];
    if (!k.startsWith("--")) continue;
    const v = argv[i + 1];
    out[k.slice(2)] = v;
    i++;
  }
  return out;
}

function slugify(raw) {
  const cleaned = (raw || "")
    .toLowerCase()
    .replace(/\.pdf$/i, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  return cleaned || "run";
}

function htmlFile(fragment) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width,initial-scale=1" />
<title>Generated page</title>
<link rel="stylesheet" href="./css/page.css" />
</head>
<body>
${fragment}
</body>
</html>
`;
}

function isFullHtmlDocument(content) {
  return /^\s*<!doctype\s+html/i.test(content) || /<html[\s>]/i.test(content);
}

function ensureCssLink(fullHtml) {
  if (/href=["']\.\/css\/page\.css["']/i.test(fullHtml)) {
    return fullHtml;
  }
  const linkTag = '<link rel="stylesheet" href="./css/page.css" />';
  const lower = fullHtml.toLowerCase();
  const headClose = lower.lastIndexOf("</head>");
  if (headClose >= 0) {
    return `${fullHtml.slice(0, headClose)}${linkTag}\n${fullHtml.slice(headClose)}`;
  }
  return `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8" />\n<meta name="viewport" content="width=device-width,initial-scale=1" />\n${linkTag}\n</head>\n<body>\n${fullHtml}\n</body>\n</html>\n`;
}

function cssFile(scopedCss) {
  return `/* Generated by pdf-to-html skill. */
*, *::before, *::after { box-sizing: border-box; }
html, body {
  margin: 0; padding: 0; background: #ffffff; color: #111;
  font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
}
img { max-width: 100%; height: auto; display: block; }

${scopedCss}

/* Keep these last so they win specificity ties. */
html, body { height: auto !important; min-height: 0 !important; }
.page-root { min-height: 0 !important; }
`;
}

/**
 * --inline-images: base64-embed every <img src="./crops/*.png"> (or any
 * relative .png/.jpg/.jpeg/.webp/.gif src) into a data: URI so content.html
 * is fully self-contained — no external crops/ dependency. Mirrors the web
 * app's inlineImageTokens (lib/claude.ts) but works on file-path srcs
 * instead of __PDF_IMAGE_<id>__ tokens. Best-effort: a src that can't be
 * read is left untouched and logged.
 */
async function inlineImages(fragment, baseDir) {
  const mimeByExt = {
    ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
    ".webp": "image/webp", ".gif": "image/gif",
  };
  const srcRe = /(<img[^>]*\bsrc=")([^"]+)("[^>]*>)/g;
  let inlined = 0, missing = 0;
  const matches = [...fragment.matchAll(srcRe)];
  for (const m of matches) {
    const url = m[2];
    if (/^(data:|https?:|\/\/)/i.test(url)) continue; // skip data/remote/protocol-relative
    const ext = path.extname(url).toLowerCase();
    const mime = mimeByExt[ext];
    if (!mime) continue;
    const abs = path.resolve(baseDir, url);
    try {
      const bytes = await readFile(abs);
      const dataUri = `data:${mime};base64,${bytes.toString("base64")}`;
      fragment = fragment.replace(m[2], dataUri);
      inlined++;
    } catch {
      missing++;
    }
  }
  return { fragment, inlined, missing };
}

async function main() {
  const args = parseArgs(process.argv);
  for (const req of ["html", "css", "out-root", "run-id", "page"]) {
    if (!args[req]) {
      console.error(JSON.stringify({ ok: false, error: `Required: --${req}` }));
      process.exit(2);
    }
  }
  let fragment = await readFile(path.resolve(args.html), "utf8");
  const scopedCss = await readFile(path.resolve(args.css), "utf8");
  const inlineRequested = Object.prototype.hasOwnProperty.call(args, "inline-images");
  const page = parseInt(args.page, 10);
  if (!Number.isFinite(page) || page < 1) {
    console.error(JSON.stringify({ ok: false, error: "--page must be a positive integer" }));
    process.exit(2);
  }

  let suffix = "";
  if (args["pdf-for-hash"]) {
    try {
      const bytes = await readFile(path.resolve(args["pdf-for-hash"]));
      const h = crypto.createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      suffix = "-" + h;
    } catch { /* hashing best-effort */ }
  }
  const runSlug = slugify(args["run-id"]) + suffix;
  const pageFolder = `page_${page}`;
  const outRoot = path.resolve(args["out-root"]);
  const pageDir = path.join(outRoot, runSlug, pageFolder);
  const cssDir = path.join(pageDir, "css");
  await mkdir(cssDir, { recursive: true });
  await writeFile(path.join(cssDir, "page.css"), cssFile(scopedCss), "utf8");

  let inlineInfo = null;
  if (inlineRequested) {
    const baseDir = path.dirname(path.resolve(args.html));
    const res = await inlineImages(fragment, baseDir);
    fragment = res.fragment;
    inlineInfo = { inlined: res.inlined, missing: res.missing };
  }

  const outputHtml = isFullHtmlDocument(fragment)
    ? ensureCssLink(fragment)
    : htmlFile(fragment);
  await writeFile(path.join(pageDir, "content.html"), outputHtml, "utf8");

  let workPaths = null;
  if (args["work-dir"]) {
    const workDir = path.resolve(args["work-dir"]);
    const workCssDir = path.join(workDir, "css");
    await mkdir(workCssDir, { recursive: true });
    const workCssPath = path.join(workCssDir, "page.css");
    const workContentPath = path.join(workDir, "content.html");
    await writeFile(workCssPath, cssFile(scopedCss), "utf8");
    await writeFile(workContentPath, outputHtml, "utf8");
    workPaths = {
      workDir,
      contentPath: workContentPath,
      cssPath: workCssPath,
    };
  }

  const reportPath = path.join(pageDir, "report.json");
  await writeFile(reportPath, JSON.stringify({
    ok: true,
    runSlug,
    page,
    contentPath: path.join(pageDir, "content.html"),
    cssPath: path.join(cssDir, "page.css"),
    reportPath,
    workPaths,
    inlineImages: inlineInfo,
  }, null, 2), "utf8");

  console.log(JSON.stringify({
    ok: true,
    runSlug,
    pageFolder,
    diskDir: pageDir,
    contentPath: path.join(pageDir, "content.html"),
    cssPath: path.join(cssDir, "page.css"),
    reportPath,
    workPaths,
    inlineImages: inlineInfo,
  }));
}

main().catch((err) => {
  console.error(JSON.stringify({ ok: false, error: err?.message ?? String(err) }));
  process.exit(1);
});
